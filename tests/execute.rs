// -- a broad sweep, so this is not just the named bugs ----------------------

#[tokio::test]
async fn a_spread_of_shapes_on_duckdb() {
    for sql in [
        "SELECT c_nationkey, c_mktsegment, sum(c_acctbal) FROM customer GROUP BY c_nationkey, c_mktsegment",
        "SELECT DISTINCT c_nationkey, c_mktsegment FROM customer",
        "SELECT c_nationkey, count(*) AS n FROM customer GROUP BY c_nationkey HAVING count(*) > 50",
        "SELECT c.c_custkey, o.o_orderkey FROM customer c LEFT JOIN orders o ON c.c_custkey = o.o_custkey",
        "SELECT c_nationkey FROM customer UNION SELECT s_nationkey FROM supplier",
        "SELECT count(*) FROM orders WHERE o_custkey NOT IN (SELECT c_custkey FROM customer WHERE c_nationkey = 1)",
        "SELECT c_custkey, (SELECT count(*) FROM orders o WHERE o.o_custkey = c.c_custkey) AS n FROM customer c",
        "SELECT c_nationkey, c_mktsegment, count(*) FROM customer GROUP BY ROLLUP(c_nationkey, c_mktsegment)",
        "SELECT o_custkey, sum(o_totalprice) AS t, rank() OVER (ORDER BY sum(o_totalprice) DESC) AS r FROM orders GROUP BY o_custkey",
    ] {
        assert_same_on_duckdb(sql).await;
    }
}

#[tokio::test]
async fn a_spread_of_shapes_on_postgres() {
    for sql in [
        "SELECT c_nationkey, c_mktsegment, sum(c_acctbal) FROM customer GROUP BY c_nationkey, c_mktsegment",
        "SELECT DISTINCT c_nationkey, c_mktsegment FROM customer",
        "SELECT c_nationkey, count(*) AS n FROM customer GROUP BY c_nationkey HAVING count(*) > 50",
        "SELECT c_nationkey FROM customer UNION SELECT s_nationkey FROM supplier",
        "SELECT count(*) FROM orders WHERE o_custkey NOT IN (SELECT c_custkey FROM customer WHERE c_nationkey = 1)",
        "SELECT c_nationkey, c_mktsegment, count(*) FROM customer GROUP BY ROLLUP(c_nationkey, c_mktsegment)",
    ] {
        assert_same_on_postgres(sql).await;
    }
}
