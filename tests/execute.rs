/// U3: `['c_name', ..., 'sum(l_quantity)']` came back with the aggregate
/// rotated to the front. Same rows, wrong columns, no error.
const Q18: &str = "SELECT c_name, c_custkey, o_orderkey, o_orderdate, o_totalprice, \
                   sum(l_quantity) FROM customer, orders, lineitem \
                   WHERE o_orderkey IN (SELECT l_orderkey FROM lineitem \
                                        GROUP BY l_orderkey HAVING sum(l_quantity) > 300) \
                     AND c_custkey = o_custkey AND o_orderkey = l_orderkey \
                   GROUP BY c_name, c_custkey, o_orderkey, o_orderdate, o_totalprice";

/// U4: returned 15 rows where 10 were asked for.
const LIMIT_OFFSET: &str =
    "SELECT c_custkey FROM customer ORDER BY c_custkey LIMIT 10 OFFSET 5";

/// U5: TPC-H Q22's shape. Returned 25 rows against a baseline of 3.
const ANTI_JOIN_FILTER: &str =
    "SELECT cc, count(*) FROM ( \
       SELECT substring(c_phone FROM 1 FOR 2) AS cc, c_acctbal FROM customer \
       WHERE substring(c_phone FROM 1 FOR 2) IN ('13','31','23') \
         AND NOT EXISTS (SELECT 1 FROM orders WHERE o_custkey = c_custkey) \
     ) t GROUP BY cc";

/// U6: nine columns instead of five, with `n_*` duplicated.
const CROSS_JOIN: &str = "SELECT * FROM nation n, (SELECT count(*) AS c FROM customer) x";

