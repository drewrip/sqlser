//! Execution tests: run sqlser's SQL on a real engine and diff it against the
//! original query.
//!
//! `BROKEN.md` is explicit that the worst failures — a rotated column order, a
//! dropped filter, an inflated `LIMIT` — produce no error and survive a
//! round-trip check. The only thing that catches them is executing both
//! queries and comparing the results, so that is what these do.
//!
//! Engines are driven through their CLIs (`duckdb`, `psql`) rather than a
//! client crate, to keep the crate's dependency surface small. A test **skips**
//! when its engine is unreachable, following `dee/tests/adbc_smoke.rs`.

mod support;

use std::process::Command;

use sqlser::Unparser;
use sqlser::dialect::{DuckDBDialect, PostgreSqlDialect};
use support::{ctx, ctx_with, opt_plan};

/// The DuckDB TPC-H fixture, regenerated by
/// `duckdb tpch.duckdb -c "INSTALL tpch; LOAD tpch; CALL dbgen(sf=0.01)"`.
fn duck_db_path() -> Option<String> {
    let p = std::env::var("TPCH_DB").unwrap_or_else(|_| "tpch.duckdb".into());
    // Tests run from the crate directory; the fixture lives at the workspace root.
    [p.clone(), format!("../{p}")]
        .into_iter()
        .find(|c| std::path::Path::new(c).exists())
}

fn duck(sql: &str) -> Option<String> {
    let db = duck_db_path()?;
    // Read-only, because these tests run concurrently against one file and
    // DuckDB takes an exclusive lock otherwise.  The `u7` case needs temp
    // views, which a read-only *database* still allows.
    let out = Command::new("duckdb")
        .args(["-readonly", &db, "-csv", "-noheader", "-c", sql])
        .output()
        .ok()?;
    if !out.status.success() {
        return Some(format!("ERROR: {}", String::from_utf8_lossy(&out.stderr)));
    }
    Some(String::from_utf8_lossy(&out.stdout).to_string())
}

fn pg(sql: &str) -> Option<String> {
    let dsn = std::env::var("PG_DSN").unwrap_or_else(|_| {
        "postgresql://runner:password@0.0.0.0:5432/benchmark".into()
    });
    let schema = std::env::var("PG_SCHEMA").unwrap_or_else(|_| "tpch".into());
    let out = Command::new("psql")
        .args([&dsn, "-tAF,", "-v", "ON_ERROR_STOP=1", "-c",
               &format!("SET search_path = {schema}"), "-c", sql])
        .output()
        .ok()?;
    if !out.status.success() {
        let err = String::from_utf8_lossy(&out.stderr);
        // Server down or database missing: skip rather than fail.
        if err.contains("could not connect") || err.contains("does not exist") {
            return None;
        }
        return Some(format!("ERROR: {err}"));
    }
    Some(String::from_utf8_lossy(&out.stdout).to_string())
}

/// Sort the rows so comparison does not depend on an unordered query's
/// arbitrary row order — but keep each row's columns in place, since column
/// order is one of the things under test.
fn normalize(s: &str) -> Vec<String> {
    let mut rows: Vec<String> = s
        .lines()
        .map(|l| l.trim().to_string())
        .filter(|l| !l.is_empty())
        .collect();
    rows.sort();
    rows
}

macro_rules! engine_or_skip {
    ($run:expr, $sql:expr, $name:literal) => {
        match $run($sql) {
            Some(v) => v,
            None => {
                eprintln!("skipping: {} is not reachable", $name);
                return;
            }
        }
    };
}

/// Every case: run the original SQL, run sqlser's SQL, demand identical rows.
async fn assert_same_on_duckdb(sql: &str) {
    let ctx = ctx().await;
    let plan = opt_plan(&ctx, sql).await;
    let ours = Unparser::new(&DuckDBDialect::new())
        .plan_to_sql(&plan)
        .expect("lowering must succeed");

    let base = engine_or_skip!(duck, sql, "duckdb");
    let got = engine_or_skip!(duck, &ours, "duckdb");
    assert!(!got.starts_with("ERROR"), "generated SQL failed:\n{ours}\n{got}");
    assert_eq!(
        normalize(&got),
        normalize(&base),
        "result differs from the original query.\noriginal: {sql}\nsqlser:   {ours}"
    );
}

async fn assert_same_on_postgres(sql: &str) {
    let ctx = ctx().await;
    let plan = opt_plan(&ctx, sql).await;
    let ours = Unparser::new(&PostgreSqlDialect::new())
        .plan_to_sql(&plan)
        .expect("lowering must succeed");

    let base = engine_or_skip!(pg, sql, "postgres");
    let got = engine_or_skip!(pg, &ours, "postgres");
    assert!(!got.starts_with("ERROR"), "generated SQL failed:\n{ours}\n{got}");
    assert_eq!(
        normalize(&got),
        normalize(&base),
        "result differs from the original query.\noriginal: {sql}\nsqlser:   {ours}"
    );
}

